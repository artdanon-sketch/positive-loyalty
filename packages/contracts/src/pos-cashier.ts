import { z } from 'zod'

/**
 * Кассир POSitive POS, от имени которого сервер кассы проводит чек или выдаёт награду.
 *
 * Сервер кассы входит одной связкой на заведение (`POS_LINK`, сотрудника в
 * токене нет), поэтому человека называет само тело запроса. Лояльность заводит
 * по `ref` своего сотрудника без входа (`Staff.posStaffRef`) — на него ложатся
 * доплата за нового гостя и отчёты «кто привёл». Владелец 19.11.2026 на «как
 * связать кассиров»: «Автоматически».
 *
 * От кассира с PIN поле не принимается: его и так знает токен, а подставить
 * чужое имя из тела значило бы начислять доплату кому угодно.
 */
export const PosCashier = z
  .object({
    /** Неизменный идентификатор сотрудника в POSitive POS. */
    ref: z.string().trim().min(1).max(64),
    /** Имя для отчётов. Меняется — догоняет при следующем чеке. */
    name: z.string().trim().min(1).max(80),
  })
  .strict()

export type PosCashier = z.infer<typeof PosCashier>
