#!/usr/bin/env node
/**
 * Ключи для уведомлений в приложении гостя (VAPID).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ. Пара ключей заводится один раз на всю установку
 * и живёт в переменных окружения сервера. Менять её нельзя без последствий:
 * все подписки, выданные под старым ключом, перестают работать молча —
 * уведомления просто не приходят, и гость об этом не узнает.
 *
 * ОТКРЫТЫЙ КЛЮЧ НЕ СЕКРЕТ: он уезжает в браузер гостя при подписке.
 * ЗАКРЫТЫЙ — настоящий секрет: кто им владеет, шлёт уведомления нашим гостям
 * от нашего имени. В репозиторий он не попадает никогда.
 *
 * Запуск: pnpm push:keys
 */

import webpush from 'web-push'

const { publicKey, privateKey } = webpush.generateVAPIDKeys()

const lines = [
  '',
  'Ключи для уведомлений созданы. Вставьте их в переменные сервера:',
  '',
  `VAPID_PUBLIC_KEY=${publicKey}`,
  `VAPID_PRIVATE_KEY=${privateKey}`,
  'VAPID_SUBJECT=mailto:ваша-почта@example.com',
  '',
  'VAPID_SUBJECT — адрес, по которому Google или Mozilla свяжутся с вами,',
  'если с уведомлениями что-то не так. Требование протокола.',
  '',
  'Закрытый ключ — секрет: он живёт только в переменных Railway.',
  'Меняя пару, вы отключаете уведомления всем, кто уже подписался.',
  '',
]

process.stdout.write(`${lines.join('\n')}\n`)
