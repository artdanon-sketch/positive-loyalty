import { createCipheriv, createDecipheriv, randomBytes } from 'node:crypto'

/**
 * Шифрование TOTP-секретов перед укладкой в базу. AES-256-GCM на node:crypto.
 *
 * ЗАЧЕМ ШИФРОВАТЬ, ЕСЛИ БАЗА И ТАК ПОД ЗАЩИТОЙ. Затем, что TOTP-секрет — не хеш.
 * Пароль в базе лежит хешем: укравший дамп не получает пароль, он получает задачу
 * на перебор. С секретом второго фактора так не выйдет — чтобы сверить код,
 * сервер должен посчитать HMAC, а значит обязан знать секрет целиком. Положив его
 * открытым текстом, мы получаем базу, из которой второй фактор просто выписывается:
 * укравший дамп генерирует правильные коды для любого админа платформы бесконечно
 * долго и молча — вход выглядит абсолютно легитимным.
 *
 * Смысл шифрования ровно один и он узкий: РАЗВЕСТИ ДВА СЕКРЕТА ПО РАЗНЫМ МЕСТАМ.
 * База живёт в Supabase, ключ — в переменной окружения Railway. Утечка одной
 * только базы (SQL-инъекция, забытый бэкап, лишний доступ у подрядчика, снапшот
 * в чужом бакете) перестаёт быть достаточной. Если утекли и база, и окружение —
 * шифрование не спасает, и обещать обратное было бы обманом: это защита от одного
 * конкретного, зато самого частого сценария.
 *
 * ПОЧЕМУ GCM. Он аутентифицирующий: при расшифровке проверяется тег, и подменённый
 * байт шифротекста даёт ошибку, а не другой секрет. Без этого свойства тот, у кого
 * есть запись в базу, но нет ключа, мог бы менять чужие секреты вслепую.
 *
 * ФОРМАТ ХРАНЕНИЯ повторяет приём из apps/api/src/auth/pin.ts: строка начинается
 * с метки алгоритма. Когда формат придётся сменить, старые записи останутся
 * читаемыми — по префиксу видно, чем их открывать, и не нужна миграция всей
 * таблицы в одном релизе.
 */

/** Метка версии формата. Всё, что начинается иначе, этим кодом не открывается. */
const PREFIX = 'gcm'

/** 12 байт — рекомендованный размер nonce для GCM: при нём режим работает без внутреннего пересчёта. */
const IV_LENGTH = 12

/** AES-256. */
const KEY_LENGTH = 32

/** Полный тег GCM. Укорачивать его — ослаблять проверку целостности ради 8 байт в строке. */
const TAG_LENGTH = 16

const ALGORITHM = 'aes-256-gcm'

/** Имя переменной окружения — то же, что описано в .env.example. */
const ENV_NAME = 'PLATFORM_TOTP_ENC_KEY'

/** Подсказка через node, а не через openssl: команда обязана работать и на Windows-машинах команды. */
const HOW_TO_GENERATE =
  "Сгенерировать: node -e \"console.log(require('node:crypto').randomBytes(32).toString('base64'))\""

/**
 * Зашифровать секрет для хранения.
 *
 * IV случайный на каждый вызов, и это не перестраховка: в GCM повторное
 * использование пары «ключ + IV» ломает не только конфиденциальность двух
 * сообщений, но и позволяет подделывать теги. Одна строка на выходе, а не три
 * колонки, — чтобы нельзя было записать шифротекст, забыв обновить тег.
 */
export function sealSecret(plaintext: string, key: Buffer): string {
  assertKey(key)

  const iv = randomBytes(IV_LENGTH)
  const cipher = createCipheriv(ALGORITHM, key, iv)
  const ciphertext = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final()])

  return [
    PREFIX,
    iv.toString('base64'),
    cipher.getAuthTag().toString('base64'),
    ciphertext.toString('base64'),
  ].join('.')
  // Точка как разделитель безопасна: в алфавите base64 её нет.
}

/**
 * Расшифровать секрет из базы.
 *
 * Сообщения об ошибках намеренно одинаково бессодержательные: «не открылось» и всё.
 * Разные тексты на «чужой ключ», «сбитый тег» и «испорченный шифротекст» — это
 * оракул, по которому подбирают содержимое, а сами сообщения к тому же попадают
 * в логи, где секретам делать нечего (CLAUDE.md, железное правило 5).
 */
export function openSecret(sealed: string, key: Buffer): string {
  assertKey(key)

  const parts = sealed.split('.')

  if (parts.length !== 4 || parts[0] !== PREFIX) {
    throw new Error(
      `openSecret: неизвестный формат записи, ожидался префикс «${PREFIX}» и четыре части через точку`,
    )
  }

  const [, ivRaw, tagRaw, ciphertextRaw] = parts

  // Buffer.from(..., 'base64') не жалуется на мусор, а молча выбрасывает лишние
  // символы. Поэтому проверяем длины сами — иначе повреждённая запись дошла бы
  // до createDecipheriv и упала там чужим, невнятным для нас сообщением.
  const iv = Buffer.from(ivRaw ?? '', 'base64')
  const tag = Buffer.from(tagRaw ?? '', 'base64')
  const ciphertext = Buffer.from(ciphertextRaw ?? '', 'base64')

  if (iv.length !== IV_LENGTH || tag.length !== TAG_LENGTH) {
    throw new Error('openSecret: запись повреждена')
  }

  try {
    const decipher = createDecipheriv(ALGORITHM, key, iv)
    decipher.setAuthTag(tag)

    // final() бросает, если тег не сошёлся: чужой ключ, правленый шифротекст и
    // сбитый IV приходят сюда одинаково — и это правильно.
    return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString('utf8')
  } catch {
    throw new Error('openSecret: не удалось расшифровать — неверный ключ или повреждённые данные')
  }
}

/**
 * Ключ из переменной окружения: base64, ровно 32 байта после декодирования.
 *
 * Падаем на старте приложения, а не на первом входе админа. Ошибка объясняет,
 * что именно не так и как это починить, но САМОГО ЗНАЧЕНИЯ не показывает: текст
 * исключения уходит в лог и в трекер, и ключ шифрования там жить не должен —
 * иначе весь смысл разнесения базы и ключа пропадает в один момент.
 */
export function keyFromEnv(raw: string | undefined): Buffer {
  if (raw === undefined || raw.trim() === '') {
    throw new Error(
      `keyFromEnv: ключ шифрования секретов второго фактора (${ENV_NAME}) не задан. ${HOW_TO_GENERATE}`,
    )
  }

  const key = Buffer.from(raw.trim(), 'base64')

  if (key.length !== KEY_LENGTH) {
    // Длина — не секрет, а единственная зацепка для того, кто это чинит:
    // по ней сразу видно «скопировали без последнего символа» или «положили hex».
    throw new Error(
      `keyFromEnv: ${ENV_NAME} должен декодироваться из base64 ровно в ${KEY_LENGTH} байт, ` +
        `а получилось ${key.length}. ${HOW_TO_GENERATE}`,
    )
  }

  return key
}

function assertKey(key: Buffer): void {
  if (key.length !== KEY_LENGTH) {
    throw new Error(`secret-box: ключ должен быть длиной ${KEY_LENGTH} байт для ${ALGORITHM}`)
  }
}
