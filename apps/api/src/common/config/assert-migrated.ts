import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { Logger } from '@nestjs/common'

/**
 * Отказ стартовать против непромигрированной базы.
 *
 * ─── ЗАЧЕМ ЭТО ЕСТЬ ─────────────────────────────────────────────────────────
 *
 * 10 сентября 2026 в бой уехал код с колонкой `LedgerEntry.saleKindId`, которой
 * в базе не было. Выходная схема записи журнала строгая, поэтому падало КАЖДОЕ
 * чтение операции, а не только новая функция: касса, бэк-офис, гостевое
 * приложение — всё сразу. Снаружи это выглядело как работающий сервис:
 * `/health` отвечал `ok`, потому что базы он не касается.
 *
 * Причина была в доставке: Railway выкатывает сервис на каждый push, а миграции
 * не применяет никто. Чинить доставку правильно, но недостаточно: доставок
 * несколько — панель Railway, workflow по тегу, ручной запуск, — и каждая может
 * однажды промолчать. Здесь проверка стоит в одном месте, через которое
 * проходит любой запуск.
 *
 * ─── ПОЧЕМУ ПАДЕНИЕ ЛУЧШЕ РАБОТЫ ────────────────────────────────────────────
 *
 * Процесс, упавший на старте, для Railway — неудачная выкатка: предыдущая
 * версия продолжает обслуживать людей. Худший исход превращается из «новый код
 * против старой базы» в «остались на старом коде со старой базой». Второе —
 * это просто отложенный релиз.
 *
 * ─── ЧЕГО ПРОВЕРКА НЕ ДЕЛАЕТ ────────────────────────────────────────────────
 *
 * Она НЕ падает, когда не может проверить: списка миграций нет, база
 * не отвечает, таблица журнала недоступна. Такое бывает и на пустой локальной
 * базе, и в тесте. Останавливать запуск из-за невозможности проверить значит
 * менять одну тихую поломку на другую — погромче, но беспричинную.
 *
 * Разница между «не сходится» и «не смог посмотреть» здесь принципиальна:
 * первое — отказ, второе — предупреждение в журнале.
 *
 * ─── ОГРАНИЧЕНИЕ ПЕРВОГО ВЫПУСКА ────────────────────────────────────────────
 *
 * Чтобы прочитать `_prisma_migrations`, роли приложения нужен явный GRANT —
 * он приезжает миграцией из этого же выпуска. Значит на самом этом релизе
 * проверка ещё скажет «не смог посмотреть». Работать по-настоящему она начнёт
 * со следующего, и это честнее, чем выдать права задним числом.
 */

/** Имя файла со списком миграций. Кладётся в dist на сборке. */
const MANIFEST = 'migrations-manifest.json'

const logger = new Logger('Migrations')

/** Строка журнала миграций Prisma. */
export interface AppliedMigration {
  migration_name: string
}

/** Как проверка ходит в базу. Отдельным типом, чтобы тест обошёлся без неё. */
export type MigrationQuery = (sql: string) => Promise<AppliedMigration[]>

export interface MigrationCheck {
  /** `false` — база отстала от кода. Запускаться нельзя. */
  readonly ok: boolean
  /** Миграции, которых в базе нет. Пусто, если проверить не удалось. */
  readonly missing: readonly string[]
  /** Почему проверить не удалось. `null` — проверка состоялась. */
  readonly skippedBecause: string | null
}

/**
 * Отбираются только ЗАКОНЧЕННЫЕ миграции.
 *
 * Прерванная миграция оставляет строку без `finished_at`. Считать такую
 * применённой значило бы пропустить запуск против наполовину изменённой базы —
 * состояния хуже, чем просто старая база.
 */
const APPLIED_SQL = 'SELECT migration_name FROM "_prisma_migrations" WHERE finished_at IS NOT NULL'

/**
 * Список миграций, с которым собран ЭТОТ образ.
 *
 * Читается из файла рядом с собранным кодом, а не из каталога `prisma/
 * migrations`: в образе этого каталога может не оказаться вовсе, и проверка
 * молча превратилась бы в «ожидаем ноль миграций» — то есть в проверку,
 * которая всегда довольна.
 *
 * `null` — прочитать не удалось. Пустой список тоже возвращается как `null`:
 * ожидать ничего эта проверка не может по смыслу.
 */
export const readExpectedMigrations = (): readonly string[] | null => {
  try {
    const raw = readFileSync(join(__dirname, '..', '..', MANIFEST), 'utf8')
    const parsed: unknown = JSON.parse(raw)

    if (!Array.isArray(parsed) || parsed.some((item) => typeof item !== 'string')) {
      return null
    }

    return parsed.length === 0 ? null : (parsed as readonly string[])
  } catch {
    return null
  }
}

/**
 * Сверить базу со списком миграций.
 *
 * Список передаётся снаружи, а не читается здесь: иначе проверить саму сверку
 * можно было бы только подсовывая файлы, и тест проверял бы файловую систему
 * вместо арифметики.
 */
export const checkMigrations = async (
  expected: readonly string[] | null,
  query: MigrationQuery,
): Promise<MigrationCheck> => {
  if (expected === null) {
    return { ok: true, missing: [], skippedBecause: `не удалось прочитать ${MANIFEST}` }
  }

  let applied: AppliedMigration[]

  try {
    applied = await query(APPLIED_SQL)
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error)
    return { ok: true, missing: [], skippedBecause: `журнал миграций недоступен: ${reason}` }
  }

  const done = new Set(applied.map((row) => row.migration_name))
  const missing = expected.filter((name) => !done.has(name))

  return { ok: missing.length === 0, missing, skippedBecause: null }
}

/**
 * Проверить и, если база отстала, остановить запуск.
 *
 * Отдельно от `checkMigrations`, потому что решение «падать» принимает точка
 * входа, а не проверка: тесту нужен результат, а не мёртвый процесс.
 */
export const assertMigrated = async (
  query: MigrationQuery,
  /** Список миграций. Параметр существует ради теста: подсовывать файлы,
   *  чтобы проверить решение «падать или нет», значило бы проверять
   *  файловую систему вместо решения. */
  expected: readonly string[] | null = readExpectedMigrations(),
): Promise<void> => {
  const result = await checkMigrations(expected, query)

  if (result.skippedBecause !== null) {
    logger.warn(
      `Не удалось сверить миграции (${result.skippedBecause}). ` +
        'Запуск продолжается: невозможность проверить — не то же самое, что несовпадение.',
    )
    return
  }

  if (!result.ok) {
    throw new Error(
      'База отстала от кода: не применены миграции — ' +
        `${result.missing.join(', ')}. Запуск остановлен намеренно: код, которому ` +
        'нужны эти изменения, против старой базы работает наполовину и молча. ' +
        'Примените их (pnpm db:deploy) и выкатывайте снова.',
    )
  }

  logger.log('Миграции сошлись с базой')
}
