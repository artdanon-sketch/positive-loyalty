/**
 * С каких адресов браузерным клиентам можно ходить в API кассы и бэк-офиса.
 *
 * Сайты (бэк-офис, карта гостя) задаёт выкладка — переменной CORS_ORIGINS:
 * их адрес меняется вместе с доменом. А вот приложения для телефона — часть
 * самого продукта: оболочка Capacitor 6 на Android открывает веб-часть
 * с https://localhost, и запросы к серверу приходят оттуда. Держать этот адрес
 * в переменной нельзя: 16.10.2026 его там не оказалось, и все APK писали
 * «сервер недоступен», хотя сервер был жив. Любая ручная правка переменной
 * (например, при переезде на свой домен) повторила бы это снова.
 *
 * Только для этого сервиса: в панель платформы (platform-main.ts) приложения
 * не ходят, и расширять доверие сервису, который видит все заведения, незачем.
 *
 * iOS-оболочки нет — её адрес (capacitor://localhost) появится здесь вместе с ней.
 */
export const NATIVE_APP_ORIGINS: readonly string[] = ['https://localhost']

export const apiCorsOrigins = (configured: readonly string[]): string[] => [
  ...new Set([...configured, ...NATIVE_APP_ORIGINS]),
]
