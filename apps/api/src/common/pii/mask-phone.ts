/**
 * Маска телефона: «+66 •• •• 4821».
 *
 * Код страны и последние четыре цифры — достаточно, чтобы гость узнал свой
 * номер на экране кассира, и мало, чтобы номер утёк с экрана или из лога
 * (docs/02, раздел 2.1; docs/05, железное правило 5).
 *
 * ПОЧЕМУ ОДНА ФУНКЦИЯ, А НЕ ТРИ. Их и было три — в admin.service, guest.service
 * и guest-auth.service, — и они уже начали расходиться: одна брала срез иначе.
 * Маскирование персональных данных не то место, где допустимы три реализации:
 * достаточно одной из них однажды показать на две цифры больше, и это будет
 * утечка, которую никто не заметит.
 *
 * ТЕЛЕФОН МОЖЕТ ОТСУТСТВОВАТЬ. С появлением входа через Google, LINE
 * и Telegram номер перестал быть обязательным: ни один из поставщиков его
 * не отдаёт. Тогда маскировать нечего, и функция возвращает null — не пустую
 * строку и не «неизвестно», чтобы вызывающий решал сам, что показать человеку.
 */
export function maskPhone(e164: string): string
export function maskPhone(e164: string | null | undefined): string | null
export function maskPhone(e164: string | null | undefined): string | null {
  if (e164 === null || e164 === undefined || e164 === '') {
    return null
  }

  return `${e164.slice(0, 3)} •• •• ${e164.slice(-4)}`
}
