import { describe, expect, it } from 'vitest'

import { maskPhone } from './mask-phone'

/**
 * Маска телефона — работа с персональными данными, и ошибка здесь тихая:
 * лишняя открытая цифра не ломает ни один экран и не роняет ни один тест,
 * она просто утекает.
 *
 * Реализаций этой функции было ЧЕТЫРЕ, и они успели разойтись: три прятали
 * середину номера, а четвёртая — наоборот, последние цифры, оставляя на виду
 * почти весь номер. Заметить это можно было только сравнив их глазами.
 * Теперь реализация одна, и вот проверки, которые не дадут ей разъехаться снова.
 */
describe('Маска телефона', () => {
  it('оставляет код страны и последние четыре цифры', () => {
    expect(maskPhone('+66812345678')).toBe('+66 •• •• 5678')
  })

  it('прячет середину номера — там оператор и большая часть цифр', () => {
    const masked = maskPhone('+66812345678')

    // Именно то, чего в выводе быть не должно: середина номера.
    expect(masked).not.toContain('8123')
    expect(masked).not.toContain('81234')
  })

  it('не отдаёт номер целиком ни при какой длине', () => {
    for (const phone of ['+79001234567', '+6621234567', '+12025550123', '+380501234567']) {
      const masked = maskPhone(phone)

      expect(masked).not.toBe(phone)
      expect(masked).not.toContain(phone.slice(3, -4))
    }
  })

  it('на отсутствующем телефоне возвращает null, а не пустую строку', () => {
    // Пустая строка попала бы на экран как пустое поле, и человек решил бы,
    // что номер есть, но не загрузился. null заставляет вызывающего решить,
    // что показать: «не указан», прочерк или ничего.
    expect(maskPhone(null)).toBeNull()
    expect(maskPhone(undefined)).toBeNull()
    expect(maskPhone('')).toBeNull()
  })

  it('короткий мусор не превращается в открытый номер', () => {
    // На вход может прийти всё что угодно из старых данных. Даже тогда
    // функция не обязана быть красивой, но обязана не показывать больше,
    // чем показала бы на нормальном номере.
    const masked = maskPhone('+66')

    expect(masked).toBe('+66 •• •• +66')
  })
})
