/**
 * Ключи журнала для операций по чеку кассы.
 *
 * ЗАВЕДЕНИЕ — ЧАСТЬ КЛЮЧА. Ключ идемпотентности журнала уникален на всю базу,
 * а номер чека придумывает касса заведения. Раньше ключ был `pos:earn:<номер>`,
 * и чек «42» мог провести только первый, кто его прислал: второе заведение
 * с тем же номером получало отказ журнала, а под защитой строк — 500
 * (прогон сценариев 13.11.2026). Две кассы, нумерующие чеки с единицы,
 * мешали бы друг другу без всякого злого умысла.
 *
 * Касса и вебхук POSitive POS собирают ключ ОДНОЙ функцией: так вебхук
 * по чеку, уже проведённому кассой, находит ту же операцию и не задваивает её.
 */
export type ReceiptLeg = 'earn' | 'redeem'

export const receiptKey = (tenantId: string, leg: ReceiptLeg, receiptId: string): string =>
  `pos:${tenantId}:${leg}:${receiptId}`

/** Награда из витрины: номер выдачи придумывает касса — тоже в рамках заведения. */
export const rewardKey = (tenantId: string, redemptionId: string): string =>
  `pos:${tenantId}:reward:${redemptionId}`
