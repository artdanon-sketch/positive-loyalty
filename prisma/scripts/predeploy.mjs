/**
 * Применение миграций перед выкаткой. Запускается Railway как preDeployCommand.
 *
 * ЗАЧЕМ ЭТО СУЩЕСТВУЕТ. Railway выкатывает сервис на каждый push в main — своей
 * связкой с GitHub, мимо наших workflow. Миграции при этом не применялись
 * никем: шаг в деплое был заглушкой, а Railway про базу не знает вовсе.
 *
 * Один раз это уже стоило живого API. В код приехала колонка LedgerEntry.
 * saleKindId, в базу — нет, а выходная схема записи журнала строгая: падало
 * КАЖДОЕ чтение операции, а не только новая функция. Узнать об этом можно было,
 * только открыв приложение.
 *
 * ПОРЯДОК ЗАДАН ТЗ, А НЕ УДОБСТВОМ. docs/06, раздел 3: миграции применяются
 * отдельным шагом ДО деплоя кода. preDeployCommand — ровно это место: команда
 * выполняется на новом образе, но до того, как он начнёт принимать запросы.
 * Упадёт она — выкатка остановится, а прежняя версия продолжит работать.
 * Это лучший из плохих исходов: остаться на старом коде со старой базой.
 *
 * ПОЧЕМУ ПРОПУСК ЗДЕСЬ ЧЕСТНЫЙ, А В CI БЫЛ НЕТ. В том же проекте Railway живёт
 * второй сервис — панель платформы. У неё СВОЯ строка подключения
 * (DATABASE_URL_PLATFORM) и роль, которой миграции не положены по замыслу:
 * она читает и не пишет. DATABASE_URL у неё нет вовсе, и отсутствие его —
 * не «забыли настроить», а «этому сервису мигрировать нечего».
 *
 * Разница с заглушкой в CI: там шаг молчал, когда работа БЫЛА нужна и просто
 * не делалась. Здесь молчание означает, что работы нет.
 */

import { spawnSync } from 'node:child_process'
import process from 'node:process'

const url = process.env['DATABASE_URL']

if (typeof url !== 'string' || url.trim() === '') {
  process.stdout.write(
    '[predeploy] DATABASE_URL не задан — это не сервис приложения (панель платформы ' +
      'ходит по DATABASE_URL_PLATFORM). Миграции пропущены.\n',
  )
  process.exit(0)
}

process.stdout.write('[predeploy] Применяю миграции: prisma migrate deploy\n')

/**
 * Через npx с ЗАКРЕПЛЁННОЙ версией, а не через локальный бинарник.
 *
 * `prisma` лежит в devDependencies корня, а собранный образ может приехать
 * без них: сборщик волен вырезать разработческие зависимости, и заметить это
 * получилось бы только упавшей выкаткой. Версия закреплена той же строкой,
 * что и в package.json: миграции обязан применять тот же Prisma, который
 * их писал.
 */
const result = spawnSync('npx', ['--yes', 'prisma@7.9.1', 'migrate', 'deploy'], {
  stdio: 'inherit',
  shell: process.platform === 'win32',
})

if (result.error !== undefined) {
  process.stderr.write(`[predeploy] Не удалось запустить prisma: ${result.error.message}\n`)
  process.exit(1)
}

process.exit(result.status ?? 1)
