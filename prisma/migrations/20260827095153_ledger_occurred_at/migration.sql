-- Время СОБЫТИЯ отдельно от времени ЗАПИСИ.
--
-- Чек приходит от кассы вебхуком, и вебхук опаздывает: связь на острове рвётся,
-- касса работает офлайн и досылает смену вечером. До этой колонки такая выгрузка
-- легла бы одним столбцом отчёта, а «загрузка по часам» показала бы девять вечера
-- вместо обеда — и владелец поставил бы акцию не на тот час.
--
-- Колонка NULLABLE, и это не лень: правило репозитория требует обратимо
-- совместимой миграции. Существующие строки не переписываются вовсе — журнал
-- append-only, UPDATE по нему запрещён триггером, и заполнить их было бы нечем.
-- NULL здесь означает «событие и запись совпадают», аналитика читает
-- coalesce("occurredAt", "createdAt").
--
-- Гранты не трогаем: они выданы на таблицу целиком, новая колонка покрыта ими
-- автоматически. Проверять это обязательно — на поколоночных грантах свежая
-- колонка оказалась бы невидимой для роли приложения.

-- AlterTable
ALTER TABLE "LedgerEntry" ADD COLUMN     "occurredAt" TIMESTAMP(3);

-- CreateIndex
CREATE INDEX "LedgerEntry_tenantId_occurredAt_idx" ON "LedgerEntry"("tenantId", "occurredAt");
