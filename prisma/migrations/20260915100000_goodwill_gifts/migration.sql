-- ─────────────────────────────────────────────────────────────────────────────
-- Подарок от заведения. docs/10, раздел 5.2 («подарить одним тапом») и 6.11.
--
-- Менеджер у стойки дарит гостю десерт за долгое ожидание — промокодом,
-- который сразу появляется у гостя в приложении. Под каждым подарком лежит
-- акция на одного гостя, и её вид должен отличаться от настоящих акций
-- заведения: подарок «за ошибку кассира» не кампания, и в будущем списке
-- акций, в отчётах и в симуляции ему не место.
--
-- Отдельное значение перечисления, а не пометка в JSON: по нему фильтруют
-- индексом и видят глазами, а пометку в JSON однажды забудут поставить.
--
-- ADD VALUE не использует новое значение в этой же миграции — Postgres этого
-- не разрешил бы внутри одной транзакции.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TYPE "OfferType" ADD VALUE IF NOT EXISTS 'GOODWILL';
