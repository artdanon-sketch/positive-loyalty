-- 20260907170000_guest_lookup_by_phone
--
-- Поиск гостя по телефону при входе по коду.
--
-- ЗАЧЕМ. Вход по коду падал с ошибкой 500, и причина та же, что была у входа
-- через Google: политика доступа пускает к строке гостя по условию
-- `id = app.guest_id`. При входе этот идентификатор ещё не объявлен, поэтому
-- запрос «есть ли гость с таким телефоном» возвращал пусто ВСЕГДА — даже для
-- существующего гостя. Дальше код пытался завести второго с тем же номером
-- и упирался в уникальность.
--
-- Объявить гостя заранее, как это сделано для Google, здесь нельзя: там
-- идентификатор известен из таблицы способов входа, а тут его и надо найти.
-- Замкнутый круг, и разрывается он ровно так же, как для устройств кассы —
-- функцией с повышенными правами.
--
-- ПОЧЕМУ ЭТО НЕ ДЫРА. Функция отдаёт ОДИН идентификатор и ничего больше:
-- ни имени, ни баланса, ни истории. И вызывается она только ПОСЛЕ проверки
-- кода — то есть тем, кто уже доказал владение номером. Узнать по ней, что
-- скрытого не знал бы владелец номера, нельзя.
--
-- Расширять возвращаемое значение нельзя: это граница, а не удобный запрос.
--
-- search_path пустой: иначе вызывающий подсовывает свою схему с таблицей
-- по имени Guest и выполняет свой код с правами владельца базы. Поэтому имена
-- внутри тела квалифицированы настоящей схемой через format().
-- ─────────────────────────────────────────────────────────────────────────────

DO $migration$
DECLARE
  target_schema text := current_schema();
BEGIN
  EXECUTE format($fmt$
    CREATE OR REPLACE FUNCTION %I.guest_id_for_phone(p_phone text)
    RETURNS text
    LANGUAGE sql
    STABLE
    SECURITY DEFINER
    SET search_path = ''
    AS $body$
      SELECT g.id
      FROM %I."Guest" g
      WHERE g."phoneE164" = p_phone
      LIMIT 1;
    $body$
  $fmt$, target_schema, target_schema);

  -- PUBLIC получает EXECUTE на функции по умолчанию — снимаем.
  EXECUTE format(
    'REVOKE ALL ON FUNCTION %I.guest_id_for_phone(text) FROM PUBLIC',
    target_schema
  );

  EXECUTE format(
    'GRANT EXECUTE ON FUNCTION %I.guest_id_for_phone(text) TO positive_app',
    target_schema
  );

  EXECUTE format(
    $c$COMMENT ON FUNCTION %I.guest_id_for_phone(text) IS
      'Разрешает телефон в идентификатор гостя при входе по коду. '
      'SECURITY DEFINER: обходит политики намеренно и отдаёт ровно один '
      'идентификатор. Вызывается только после проверки кода. '
      'Расширять возвращаемое значение нельзя — это граница изоляции.'$c$,
    target_schema
  );
END
$migration$;
