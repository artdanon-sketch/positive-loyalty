-- Код промокода уникален внутри заведения, а не на всю базу.
--
-- Промокод аккаунта POSitive (POST /v1/pos/grants) кладётся гостю в кошельки
-- нескольких заведений одним и тем же кодом — тем, что гостю прислали в
-- сообщении. Погашение всегда идёт в контексте заведения (RLS + tenantId в
-- запросе), так что одинаковый текст в двух заведениях не смешивается.
--
-- Существующие коды глобально уникальны, значит и попарно (tenantId, code) —
-- новый индекс создаётся без конфликтов. Сначала новый, потом снос старого:
-- между двумя командами уникальность не пропадает ни на миг.

CREATE UNIQUE INDEX "OfferGrant_tenantId_code_key" ON "OfferGrant"("tenantId", "code");

DROP INDEX "OfferGrant_code_key";
