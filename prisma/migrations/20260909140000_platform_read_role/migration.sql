-- ─────────────────────────────────────────────────────────────────────────────
-- 20260909140000_platform_read_role
--
-- Вторая роль базы: positive_platform. Ею будет ходить ОТДЕЛЬНОЕ приложение
-- админки платформы, и только оно.
--
-- ─── ЗАЧЕМ ВООБЩЕ ВТОРАЯ РОЛЬ ────────────────────────────────────────────────
--
-- Владельцу продукта нужно видеть все заведения сразу: подписки, обороты,
-- партнёрства, акции. Обычная роль positive_app этого не может и не должна:
-- её политики RLS отсекают всё, кроме объявленного тенанта.
--
-- Соблазнительный путь — открыть кросс-тенантное чтение существующей роли
-- и городить проверки в коде: «этот маршрут только для админа платформы».
-- Этот путь отвергнут сознательно. Владельцев заведений и владельца платформы
-- обслуживал бы ОДИН процесс с ОДНОЙ ролью базы, и единственным, что отделяет
-- ресторан от оборотов конкурента, был бы забытый декоратор. Ровно этот класс
-- защиты — прикладной, а не серверный — в проекте ломался дважды (PR #38, #39).
--
-- Здесь граница проходит по роли базы. Приложение владельцев подключается
-- строкой positive_app и физически не может прочитать чужое: ни забытый
-- декоратор, ни новый маршрут, ни копипаст контроллера этого не изменят.
--
-- ─── ЧТО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ ──────────────────────────────────────────────
--
-- Роль создаётся БЕЗ ПРАВА ВХОДА (NOLOGIN) — тот же приём, что у positive_app
-- в миграции 20260826120000. Пароль и LOGIN выдаёт администратор среды отдельно,
-- вне репозитория. До этого момента роль существует и не может подключиться,
-- то есть накат этой миграции сам по себе ничего не открывает.
--
-- ─── ПОЧЕМУ ЯВНЫЕ ПОЛИТИКИ, А НЕ BYPASSRLS ───────────────────────────────────
--
-- Атрибут роли BYPASSRLS дал бы доступ ко ВСЕМУ, включая таблицы, которых ещё
-- нет. Новая таблица с секретами стала бы читаемой в момент создания, молча.
--
-- Явная политика на каждую таблицу ведёт себя наоборот: новая таблица для этой
-- роли невидима, пока кто-то осознанно не напишет ей политику на ревью миграции.
-- Забыть здесь — значит получить отказ, а не утечку. Это единственно верное
-- направление отказа для роли, которая видит всех.
--
-- Существующие политики висят на public и потому применяются и к этой роли.
-- Политики permissive, то есть складываются по ИЛИ: своя политика с USING (true)
-- открывает роли всю таблицу, а для positive_app ничего не меняется — политика
-- адресована другой роли и на него не распространяется.
--
-- ─── ПРАВА ВЫДАНЫ ПОКОЛОНОЧНО ТАМ, ГДЕ ЛЕЖИТ ЛИЧНОЕ ──────────────────────────
--
-- Владельцу платформы нужны СЧЁТА И СУММЫ, а не имена и телефоны. Postgres
-- умеет выдавать SELECT на отдельные колонки, и здесь это использовано:
--
--   Guest  — телефон, имя и день рождения НЕ выданы. Роль видит id, язык,
--            режим и даты: этого хватает на «сколько у кого гостей» и на
--            разбивку турист/резидент, и не хватает, чтобы узнать человека.
--   Staff  — pinHash НЕ выдан ни при каких обстоятельствах: это учётные данные.
--            Имя и телефон сотрудника тоже не выданы — для счёта сотрудников
--            они не нужны, а PDPA лишнего не прощает.
--
-- Таблицы, не упомянутые ниже, роли недоступны, и это не упущение:
--   PosLink            — хранит webhookSecret, то есть ключ подписи вебхуков;
--   Session, GuestSession, OtpRequest, GuestIdentity, TelegramLoginRequest
--                      — хеши токенов и одноразовых кодов;
--   StaffDevice, TransactionPreview, WebhookEvent, WebhookDelivery
--                      — для панели пока не нужны, а «пока не нужны» означает
--                        «не выдаём»: расширить список дешевле, чем объяснять
--                        утечку.
--
-- ─── РОЛЬ ТОЛЬКО ЧИТАЕТ ──────────────────────────────────────────────────────
--
-- Ни INSERT, ни UPDATE, ни DELETE по данным заведений не выдано. Панель сейчас
-- смотрит, а не правит. Единственное исключение — AuditLog: туда роль обязана
-- дописывать собственные действия, иначе просмотр чужих данных не оставит следа.
-- И читать аудит — тоже её работа: у positive_app этого права нет намеренно.
-- ─────────────────────────────────────────────────────────────────────────────

-- ── Роль ─────────────────────────────────────────────────────────────────────

DO $create_role$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'positive_platform') THEN
    -- NOLOGIN намеренно: право входа и пароль выдаёт администратор среды.
    CREATE ROLE positive_platform NOLOGIN;
  END IF;
END
$create_role$;

-- ── Доступ к схеме ───────────────────────────────────────────────────────────
--
-- Схема вычисляется, а не вписана буквой: на общей с чужим продуктом базе
-- вписанное имя изменило бы права в схеме соседа (см. 20260828100000).

DO $grant_usage$
DECLARE
  target_schema text := current_schema();
BEGIN
  EXECUTE format('GRANT USAGE ON SCHEMA %I TO positive_platform', target_schema);
END
$grant_usage$;

-- ── Права на чтение: полные там, где личного нет ─────────────────────────────

GRANT SELECT ON TABLE "Tenant" TO positive_platform;
GRANT SELECT ON TABLE "Membership" TO positive_platform;
GRANT SELECT ON TABLE "LedgerEntry" TO positive_platform;

-- ── Права на чтение: поколоночные там, где личное есть ───────────────────────

GRANT SELECT ("id", "locale", "mode", "modeLockedBy", "createdAt", "lastSeenAt")
  ON TABLE "Guest" TO positive_platform;

GRANT SELECT ("id", "tenantId", "role", "isActive", "createdAt", "lastSeenAt")
  ON TABLE "Staff" TO positive_platform;

-- ── Аудит: читать и дописывать ───────────────────────────────────────────────

GRANT SELECT, INSERT ON TABLE "AuditLog" TO positive_platform;

-- ── Политики RLS для новой роли ──────────────────────────────────────────────
--
-- По одной на таблицу, только на чтение. Адресованы конкретной роли, поэтому
-- на positive_app не влияют: у него остаётся прежняя политика на public.

CREATE POLICY platform_reads_all ON "Tenant"
  FOR SELECT TO positive_platform USING (true);

CREATE POLICY platform_reads_all ON "Membership"
  FOR SELECT TO positive_platform USING (true);

CREATE POLICY platform_reads_all ON "LedgerEntry"
  FOR SELECT TO positive_platform USING (true);

CREATE POLICY platform_reads_all ON "Guest"
  FOR SELECT TO positive_platform USING (true);

CREATE POLICY platform_reads_all ON "Staff"
  FOR SELECT TO positive_platform USING (true);

-- AuditLog: две политики, потому что права разные.
-- Читать — всё; дописывать — только свои записи, но проверять авторство в базе
-- нечем, поэтому WITH CHECK (true), а честность записи обеспечивает приложение.

CREATE POLICY platform_reads_audit ON "AuditLog"
  FOR SELECT TO positive_platform USING (true);

CREATE POLICY platform_appends_audit ON "AuditLog"
  FOR INSERT TO positive_platform WITH CHECK (true);

-- ── Умолчаний на будущие таблицы НЕТ, и это решение ──────────────────────────
--
-- ALTER DEFAULT PRIVILEGES для этой роли не задаётся намеренно. У positive_app
-- такое умолчание есть, и оно уже сыграло злую шутку: новая таблица получает
-- права молча, поэтому забытый ENABLE ROW LEVEL SECURITY означает не отказ,
-- а открытую таблицу (сторож rls-coverage появился именно из-за этого).
--
-- Для роли, которая видит все заведения сразу, повторять эту схему нельзя.
-- Пусть новая таблица будет ей недоступна, пока её не выдадут осознанно.

COMMENT ON ROLE positive_platform IS
  'Только чтение для отдельного приложения админки платформы. Личные данные '
  'гостей и сотрудников не выданы поколоночно; таблицы с секретами не выданы вовсе.';
