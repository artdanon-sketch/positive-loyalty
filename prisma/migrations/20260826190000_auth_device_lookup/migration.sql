-- ─────────────────────────────────────────────────────────────────────────────
-- Разрешение устройства в заведение до аутентификации.
--
-- ЗАДАЧА. Вход кассира по PIN — эндпоинт БЕЗ токена. Заведение определяется по
-- устройству: `deviceId` глобально уникален и зарегистрирован владельцем
-- (docs/05, раздел 2). Но прочитать StaffDevice под ролью приложения нельзя:
-- политика RLS требует объявленного `app.tenant_id`, а он-то и неизвестен.
-- Курица и яйцо.
--
-- ПОЧЕМУ НЕ ПРОЩЕ. Рассматривал два очевидных варианта и отклонил оба:
--
--   • принимать tenantId телом запроса — прямое нарушение железного правила 2
--     из CLAUDE.md и подсказка перебирающему: по разнице ответов видно,
--     существует заведение или нет;
--   • ходить этим запросом владельцем базы — владелец игнорирует ВСЕ политики,
--     то есть ради одной строки открывался бы доступ ко всему.
--
-- РЕШЕНИЕ. Функция SECURITY DEFINER выполняется с правами владельца, но отдаёт
-- РОВНО ОДНО значение — идентификатор заведения — и только для активного
-- устройства. Ни PIN, ни состав сотрудников, ни что-либо ещё через неё не видно.
-- Это минимально возможная брешь в границе, и она описана здесь целиком.
--
-- search_path зафиксирован пустым: без этого владелец схемы, подсунувший свою
-- таблицу с именем StaffDevice, выполнил бы свой код с правами владельца базы.
-- Классическая дыра SECURITY DEFINER, и она стоит одной строки.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.auth_tenant_for_device(p_device_id text)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT d."tenantId"
  FROM public."StaffDevice" d
  JOIN public."Staff" s ON s.id = d."staffId"
  WHERE d."deviceId" = p_device_id
    AND d."isActive"
    AND d."revokedAt" IS NULL
    AND s."isActive"
  LIMIT 1;
$$;

-- Никому, кроме роли приложения: PUBLIC получает EXECUTE на функции по умолчанию.
REVOKE ALL ON FUNCTION public.auth_tenant_for_device(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.auth_tenant_for_device(text) TO positive_app;

COMMENT ON FUNCTION public.auth_tenant_for_device(text) IS
  'Разрешает зарегистрированное устройство в tenantId до аутентификации. '
  'SECURITY DEFINER: обходит RLS намеренно и отдаёт только один идентификатор. '
  'Расширять возвращаемое значение нельзя — это граница изоляции.';
