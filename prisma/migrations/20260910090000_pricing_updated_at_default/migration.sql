-- Умолчание для PartnershipPricing.updatedAt.
--
-- ЗАЧЕМ. `@updatedAt` в Prisma — свойство КЛИЕНТА, а не базы: значение
-- подставляет Prisma при записи, и в саму колонку никакого DEFAULT не попадает.
-- Пока пишет только Prisma, разницы не видно.
--
-- Разница появляется, как только в таблицу пишут сырым SQL — а это миграции,
-- seed и разовые скрипты администратора. Такая запись падает с «null value in
-- column updatedAt violates not-null constraint», причём в момент, когда автор
-- уверен, что заполнил все поля: колонки-то в его INSERT нет вовсе.
--
-- Поймано ровно так: тест изоляции добавлял строку прайса сырым запросом и
-- упал в CI. Ошибка честная, но чинить её в каждом будущем скрипте — плохой
-- размен по сравнению с одной строкой здесь.
--
-- ПОЧЕМУ ЭТО НЕ МАСКИРУЕТ ОШИБКУ. Prisma продолжает подставлять значение сама
-- и при вставке, и при обновлении; умолчание срабатывает только там, где
-- колонку не указали вовсе. Смысл поля — «когда последний раз меняли» —
-- сохраняется в обоих случаях.
--
-- Единственная колонка с @updatedAt во всей схеме, поэтому образца, которому
-- надо следовать, не было — образец задаётся здесь.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE "PartnershipPricing"
  ALTER COLUMN "updatedAt" SET DEFAULT CURRENT_TIMESTAMP;

COMMENT ON COLUMN "PartnershipPricing"."updatedAt" IS
  'Умолчание в базе намеренно: @updatedAt у Prisma работает только на стороне '
  'клиента, и запись сырым SQL без него падает.';
