--
-- Аудит-лог: кто, что, когда, откуда и с какой причиной.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ЛОГИ. docs/05, раздел 9 требует именно таблицу
-- и перечисляет, что обязано в неё попадать: изменение конфига программы,
-- ручная правка баланса, отмена операции, просмотр полного телефона, экспорт
-- базы, вход админа платформы, impersonate. Логи ротируются и теряются;
-- запись «поддержка смотрела телефоны чужих гостей» теряться не должна.
--
-- ЭТА ТАБЛИЦА — ПРЕДУСЛОВИЕ АДМИНКИ ПЛАТФОРМЫ, а не украшение к ней. Ничто,
-- что видит данные чужого заведения, не имеет права появиться раньше следа,
-- который оно оставляет.
--
-- ПРАВА ЗДЕСЬ УСТРОЕНЫ НАОБОРОТ ОБЫЧНОГО. Приложению дан ровно INSERT:
--
--   SELECT  — отобран. Аудит читает админка платформы своей ролью (появится
--             отдельной миграцией). Ошибка в обычном API не должна уметь
--             выгрузить журнал наблюдений наружу.
--   UPDATE  — отобран. Запись, которую можно исправить, доказательством не является.
--   DELETE  — не выдавался. Срок хранения 24 месяца (docs/05, раздел 9)
--             обслуживается владельцем базы отдельным заданием: право удалять
--             старое не то же самое, что право удалять неудобное.
--
-- ОТБИРАТЬ ПРИХОДИТСЯ ЯВНО, И ЭТО НЕ ПЕРЕСТРАХОВКА. В миграции
-- 20260828100000 стоит ALTER DEFAULT PRIVILEGES ... GRANT SELECT, INSERT,
-- UPDATE TO positive_app. Проверено опытом на боевой базе: таблица, созданная
-- БЕЗ единого GRANT, немедленно имеет INSERT, SELECT, UPDATE. То есть без
-- REVOKE ниже аудит был бы обычной таблицей, которую приложение читает и правит.
--
-- ПОЧЕМУ ПИСАТЬ ПРИДЁТСЯ ЧЕРЕЗ $executeRaw. Prisma после create() ВСЕГДА
-- читает строку обратно (RETURNING), а SELECT здесь отобран — create() упал бы.
-- Это не обходной путь, а прямое следствие права «только дописывать»:
-- тот, кто пишет в аудит, не должен уметь его читать.
--
-- ПОЧЕМУ ОТДЕЛЬНОЕ ПЕРЕЧИСЛЕНИЕ AuditActorType, А НЕ ОБЩЕЕ ActorType.
-- В ActorType нет и не должно быть PLATFORM_ADMIN: это перечисление живёт
-- в LedgerEntry, где админ платформы не появляется никогда — по матрице
-- docs/05, раздел 3 ему запрещены любые операции с баллами. Расширять его
-- ради аудита значило бы завести в журнале денег субъекта, которому там
-- нечего делать, и заставить весь код журнала обрабатывать невозможный случай.
-- ─────────────────────────────────────────────────────────────────────────────

-- CreateEnum
--
-- Повторяет Role (CASHIER, MANAGER, OWNER, PLATFORM_ADMIN) и добавляет двух
-- субъектов, которых в Role нет и быть не может: SYSTEM для фоновых заданий
-- и GUEST для действий самого гостя. Роли перечислены поимённо, а не одним
-- STAFF: в разборе инцидента «кассир отменил операцию» и «управляющий отменил
-- операцию» — это два разных события, и различать их постфактум будет нечем.
CREATE TYPE "AuditActorType" AS ENUM ('SYSTEM', 'GUEST', 'CASHIER', 'MANAGER', 'OWNER', 'PLATFORM_ADMIN');

-- CreateTable
CREATE TABLE "AuditLog" (
    "id" TEXT NOT NULL,
    "occurredAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- NULL означает «действие вне заведения»: вход админа платформы, правка
    -- общего прайсинга. Колонка nullable намеренно — принуждать платформенные
    -- события к какому-нибудь tenantId значило бы их подделывать.
    "tenantId" TEXT,

    "actorType" "AuditActorType" NOT NULL,
    "actorId" TEXT,

    -- Что произошло, машиночитаемо: IMPERSONATE_START, PHONE_REVEALED,
    -- BALANCE_ADJUSTED, PROGRAM_CONFIG_CHANGED, DATABASE_EXPORTED.
    "action" TEXT NOT NULL,

    "entityType" TEXT,
    "entityId" TEXT,

    -- Старое и новое значение. JSON, потому что форма зависит от действия,
    -- а выдумывать общую колонку под все случаи — значит не описать ни один.
    "oldValue" JSONB,
    "newValue" JSONB,

    -- Причина текстом. Для impersonate обязательна (docs/02, раздел 6);
    -- проверяется в коде, а не ограничением: обязательность зависит от action.
    "reason" TEXT,

    "ip" TEXT,
    "userAgent" TEXT,
    "requestId" TEXT,

    CONSTRAINT "AuditLog_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
--
-- Три способа спросить журнал, три индекса. Без них первый же разбор инцидента
-- на таблице в миллионы строк превратится в полный перебор.
CREATE INDEX "AuditLog_tenantId_occurredAt_idx" ON "AuditLog"("tenantId", "occurredAt" DESC);
CREATE INDEX "AuditLog_actorType_actorId_occurredAt_idx" ON "AuditLog"("actorType", "actorId", "occurredAt" DESC);
CREATE INDEX "AuditLog_action_occurredAt_idx" ON "AuditLog"("action", "occurredAt" DESC);

-- ── Права: только дописывать ─────────────────────────────────────────────────

REVOKE ALL ON TABLE "AuditLog" FROM positive_app;
GRANT INSERT ON TABLE "AuditLog" TO positive_app;

-- ── RLS ──────────────────────────────────────────────────────────────────────
--
-- RLS включён, хотя SELECT и так отобран. Причина та же, что у
-- TelegramLoginRequest: включённый RLS без подходящей политики запрещает всё,
-- выключенный — разрешает всё и молча переживёт любую будущую выдачу прав.
-- Второй рубеж не отменяется тем, что первый сегодня закрыт.
--
-- Политика ровно одна и только на вставку. Ни USING, ни политики на SELECT
-- здесь нет намеренно: читать эту таблицу обычному приложению нечем.

ALTER TABLE "AuditLog" ENABLE ROW LEVEL SECURITY;

CREATE POLICY append_only ON "AuditLog"
  FOR INSERT WITH CHECK (true);

COMMENT ON TABLE "AuditLog" IS
  'След действий, которые docs/05 раздел 9 требует хранить 24 месяца. '
  'Приложение может только дописывать: SELECT и UPDATE отобраны, DELETE не выдан.';
