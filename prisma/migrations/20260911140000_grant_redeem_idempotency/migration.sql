-- Номер чека, в котором погасили промокод. Он же ключ идемпотентности.
--
-- ЗАЧЕМ. Железное правило 3 (CLAUDE.md) требует, чтобы повтор финансовой
-- мутации возвращал ПЕРВЫЙ ответ, а не ошибку. Погашение промокода —
-- финансовая мутация: заведение отдаёт товар.
--
-- Без этой колонки повтор выглядел бы так. Касса гасит код, сервер погашает,
-- ответ теряется в сети. Касса повторяет — и получает «код уже погашен».
-- Кассир решает, что операция не прошла, и подарок гостю не отдаёт, хотя
-- в базе код уже сгорел. Гость уходит ни с чем, спорить ему нечем.
--
-- Ровно эта ошибка уже была разобрана на проведении чека: там ключом служит
-- номер чека, а не заголовок запроса, потому что касса, потерявшая связь,
-- шлёт повтор с НОВЫМ заголовком, но с тем же чеком (docs/01, раздел 4.4).
-- Здесь то же самое и по той же причине.
--
-- NULLABLE И БЕЗ ЗАПОЛНЕНИЯ СТАРЫХ СТРОК. NULL означает «погашено без номера
-- чека» — так гасят коды, выданные до появления колонки, и так можно гасить
-- сейчас, если касса номер не передала. Повтор без номера идемпотентным
-- не будет, и это честно: сопоставить его не с чем.
--
-- UNIQUE ЗДЕСЬ НЕ НУЖЕН. Один чек может погасить несколько кодов — гость
-- предъявил два подарка сразу. Уникальна пара «код + чек», но код и так
-- уникален, а погашение атомарно: условие state = 'ISSUED' стоит внутри
-- самого UPDATE.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE "OfferGrant" ADD COLUMN "redeemedReceiptId" TEXT;

COMMENT ON COLUMN "OfferGrant"."redeemedReceiptId" IS
  'Чек, в котором погасили код. Ключ идемпотентности повтора: тот же чек '
  'возвращает первый ответ вместо GRANT_ALREADY_USED.';
