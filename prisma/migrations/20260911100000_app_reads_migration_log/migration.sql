--
-- Записывать по-прежнему может только владелец: приложение не должно уметь
-- отметить миграцию применённой, не применив её.
--
-- ОБЕИМ РОЛЯМ. Панель платформы — второй процесс с той же схемой и тем же
-- риском: код, уехавший вперёд базы, ломает её так же тихо.
--
-- СЛЕДСТВИЕ ДЛЯ ЭТОГО ЖЕ ВЫПУСКА. Пока эта миграция не применена, проверка
-- на старте прочитать журнал не сможет и честно скажет «не смог посмотреть»,
-- пропустив запуск. По-настоящему она заработает со следующего релиза.
-- Выдать права задним числом было нельзя: миграции и есть тот механизм,
-- которым права появляются.
