--
-- Защита от повторного использования кода второго фактора.
--
-- ЗАЧЕМ. RFC 6238, раздел 5.2 требует прямо: удачно проверенный код не должен
-- приниматься второй раз. Без этого подсмотренный код живёт все 30 секунд
-- своего окна, а с допуском на расхождение часов телефона и сервера — до
-- полутора минут. Этого достаточно, чтобы подсмотренным через плечо кодом
-- успели воспользоваться.
--
-- КАК. Храним номер последнего ПРИНЯТОГО окна. Проверка «пришедшее окно должно
-- быть строго больше принятого» отсекает сразу два случая: повтор того же кода
-- и попытку отмотать время назад, предъявив код из прошлого окна.
--
-- Номер окна, а не сам код: код — это секрет на 30 секунд, и хранить его
-- незачем; номер окна секретом не является вовсе.
--
-- ПОЧЕМУ ОТДЕЛЬНОЙ МИГРАЦИЕЙ, А НЕ В 20260909170000. Та уже накачена на общую
-- базу, и Prisma держит её контрольную сумму: правка накаченного файла ломает
-- следующий же деплой. Дописать колонку отдельной миграцией дешевле и честнее,
-- чем сносить и накатывать заново таблицы на боевой базе ради красоты истории.
--
-- Колонка nullable — обратимо совместимо (CLAUDE.md, «Как менять схему базы»).
-- NULL означает «второй фактор ещё ни разу не принимался», и это ровно то,
-- что верно для всех существующих строк.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE "PlatformAdmin" ADD COLUMN "lastTotpCounter" BIGINT;

COMMENT ON COLUMN "PlatformAdmin"."lastTotpCounter" IS
  'Номер последнего принятого окна TOTP. Код из этого или более раннего окна '
  'повторно не принимается — RFC 6238, раздел 5.2.';
